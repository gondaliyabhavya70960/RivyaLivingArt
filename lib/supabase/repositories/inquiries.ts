export type InquiryFilter = {
  readonly kind?: Database['public']['Enums']['inquiry_kind']
  readonly status?: Database['public']['Enums']['inquiry_status']
  readonly assignedTo?: string
  readonly limit?: number
  readonly offset?: number
}

export async function listInquiriesForStudio(
  client: Client,
  filter: InquiryFilter = {},
): Promise<Inquiry[]> {
  const from = filter.offset ?? 0
  const to = from + (filter.limit ?? 50) - 1

  let query = client.from('inquiries').select('*')
  if (filter.kind !== undefined) query = query.eq('kind', filter.kind)
  if (filter.status !== undefined) query = query.eq('pipeline_status', filter.status)
  if (filter.assignedTo !== undefined) query = query.eq('assigned_to', filter.assignedTo)

  const { data, error } = await query
    .order('created_at', { ascending: false })
    .order('id', { ascending: true })
    .range(from, to)

  if (error) throw toRepositoryError(ENTITY, 'list', 'studio', error)
  return parseRows(ENTITY, inquirySchema, data ?? [])
}

/** One enquiry, or `null` when this role cannot see it — which is indistinguishable from absent. */
export async function getInquiryForStudio(client: Client, id: string): Promise<Inquiry | null> {
  const { data, error } = await client.from('inquiries').select('*').eq('id', id).maybeSingle()
  if (error) throw toRepositoryError(ENTITY, 'get', id, error)
  return data === null ? null : parseRow(ENTITY, inquirySchema, data)
}

