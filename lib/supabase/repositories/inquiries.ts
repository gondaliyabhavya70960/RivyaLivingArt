import type { SupabaseClient } from '@supabase/supabase-js'
import { z } from 'zod'

import type { Database } from '../database.types'
import { PermissionError } from '../errors'
import {
  inquiryAttachmentSchema,
  inquiryEventSchema,
  inquirySchema,
  referenceCodeSchema,
  type Inquiry,
  type InquiryAttachment,
  type InquiryEvent,
} from '../schemas'
import { parseRow, parseRows, toRepositoryError } from './support'

type Client = SupabaseClient<Database>

const ENTITY = 'inquiry'

/**
 * `inquiries` and its two companions — the only module that reads or writes them.
 *
 * THE PUBLIC WRITE PATH USES THE ANONYMOUS CLIENT ON PURPOSE. Every other write in this codebase
 * runs behind `requirePermission`; this one has no session to check, because D1 forbids customer
 * accounts and the person filling in the form is nobody. So the RLS policy is the whole guard, and
 * using the service-role client here would bypass the one thing standing between an HTML form and
 * the table. `createInquiry` takes an ordinary client and expects to be handed the anon one.
 *
 * IT DOES NOT READ BACK, AND CANNOT. PostgreSQL applies a table's SELECT policy to an INSERT's
 * RETURNING clause, and `inquiries` has no anon SELECT policy — so `.select()` on the insert would
 * fail with `new row violates row-level security policy`, which reads exactly like a rejected write
 * and is not one. The id is generated by the CALLER and passed in; the reference code, which a
 * trigger allocates, comes back from `inquiryReferenceCode()`. Amendment A20 records the finding.
 *
 * EVERYTHING ELSE IS STAFF WORK and goes through the request-scoped session client, so RLS refuses
 * underneath the permission check as well as beside it.
 */

/**
 * Write the enquiry. Returns nothing, because there is nothing it is allowed to read.
 *
 * THE CALLER OWNS THE `id`. That is what makes the rest of the flow possible without giving `anon`
 * a select policy: the caller already holds the identifier of the row it just wrote, and every
 * follow-up — the reference code, the attachments, the handoff record — is addressed by it.
 */
export type InquiryInsert = Omit<
  Database['public']['Tables']['inquiries']['Insert'],
  'reference_code'
>

export async function createInquiry(client: Client, values: InquiryInsert): Promise<void> {
  /*
   * `reference_code` IS OMITTED FROM THE PARAMETER AND FROM THE PAYLOAD, and the cast is what says
   * so out loud. The column is `not null` with no default, so the generated types require it; the
   * BEFORE trigger allocates it and OVERWRITES anything supplied, so sending a value would be
   * sending something the database throws away. Widening the column with a default would weaken the
   * shape CHECK to accommodate a placeholder nothing ever reads.
   */
  const { error } = await client
    .from('inquiries')
    .insert(values as Database['public']['Tables']['inquiries']['Insert'])
  if (error) throw toRepositoryError(ENTITY, 'insert', values.id ?? '(new)', error)
}

/** The trigger-allocated code, for an enquiry created in the last ten minutes. */
export async function inquiryReferenceCode(client: Client, inquiryId: string): Promise<string> {
  const { data, error } = await client.rpc('inquiry_reference_code', { p_inquiry_id: inquiryId })
  if (error) throw toRepositoryError(ENTITY, 'reference-code', inquiryId, error)

  const parsed = referenceCodeSchema.safeParse(data)
  // No code came back for a row that was just written: the ten-minute window is the only thing that
  // can do that, and a clock that far out is worth failing on rather than papering over.
  if (!parsed.success) throw new PermissionError('reference-code', ENTITY)
  return parsed.data
}

/**
 * Turn the visitor's uploaded references into asset rows and link them. Returns how many landed.
 *
 * A REFERENCE OUTSIDE THE INCOMING FOLDER IS NOT ATTACHED AND NOT REPORTED. The function refuses it
 * silently, because saying which `public_id` was rejected tells a caller which ones exist.
 */
export async function attachInquiryReferences(
  client: Client,
  inquiryId: string,
  references: readonly { publicId: string; filename: string }[],
): Promise<number> {
  const { data, error } = await client.rpc('attach_inquiry_references', {
    p_inquiry_id: inquiryId,
    p_references:
      references as unknown as Database['public']['Tables']['inquiries']['Row']['answers'],
  })
  if (error) throw toRepositoryError(ENTITY, 'attach-references', inquiryId, error)
  return z.number().int().catch(0).parse(data)
}

/**
 * Record what happened to the handoff. `false` means the row had already moved on.
 *
 * IT NEVER THROWS FOR A ROW THAT WAS NOT UPDATED, because by the time this runs the enquiry is
 * SAVED — which is the outcome that matters — and failing here would turn a bookkeeping miss into a
 * visible error on a submission that succeeded.
 */
export async function recordInquiryHandoff(
  client: Client,
  inquiryId: string,
  state: 'REDIRECTED' | 'SHORTENED' | 'UNAVAILABLE',
  level: number | null,
): Promise<boolean> {
  const { data, error } = await client.rpc('record_inquiry_handoff', {
    p_inquiry_id: inquiryId,
    p_state: state,
    p_level: level,
  })
  if (error) throw toRepositoryError(ENTITY, 'record-handoff', inquiryId, error)
  return data === true
}

