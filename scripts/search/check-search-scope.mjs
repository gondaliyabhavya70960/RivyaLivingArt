#!/usr/bin/env node
/**
 * SEARCH SCOPE GATE (Phase 23)
 *
 * The public search path may not name anything research-shaped, and the research index may not be
 * reachable from a file a visitor's request can execute. This walks the import graph from every
 * public search entry point and fails on a research identifier anywhere in it.
 *
 * WHY A GATE AND NOT A CODE REVIEW. `search_documents` cannot physically hold a research row — the
 * `entity_type` CHECK in 0210 refuses one — so the schema already covers the worst case. What the
 * schema cannot cover is somebody adding a SECOND query to the suggest endpoint that reads
 * `research_search_documents` directly, "just to let staff search everything from one box". That
 * change compiles, passes every type check, and is a disclosure of competitor research through a
 * public, edge-cached GET endpoint. It fails here.
 *
 * IT IS THE NARROW SIBLING OF `check-research-isolation.mjs` (Phase 25), which enforces the same
 * boundary across the whole of `app/(site)/**`, `lib/cms/**`, `lib/catalog/**`, `lib/seo/**`,
 * `components/sections/**` and `content/**`. This one exists two phases earlier because the search
 * path is where the two corpora come closest to each other, and it keeps its own name so a failure
 * points at the search code rather than at a subsystem that does not exist yet.
 *
 * Exit 1 on any violation. Runs in `npm run check` and in CI.
 */
import { existsSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'

import { stripCommentsAndStrings } from '../db/strip-code.mjs'

const ROOT = process.cwd()

/**
 * The public search path: what a visitor's request executes when they search.
 *
 * The page and the suggest endpoint are the two entry points; everything they import is walked.
 * `lib/search/**` is not listed separately because both entry points import it, and a module in
 * there that nothing imports is not on the path.
 */
const ENTRIES = [
  join(ROOT, 'app', '(site)', 'search', 'page.tsx'),
  join(ROOT, 'app', 'api', 'search', 'suggest', 'route.ts'),
  join(ROOT, 'components', 'patterns', 'SearchCombobox', 'index.tsx'),
  join(ROOT, 'components', 'patterns', 'SearchResultCard.tsx'),
]

/**
 * The identifiers a public search file may not contain.
 *
 * `scraper` is included alongside the two research spellings because the Phase 25 fetcher lives at
 * `lib/scraper/**`, and an import of it is exactly as bad as a reference to the table.
 */
const FORBIDDEN = /research_|researchProduct|researchSearch|\bscraper\b/i

/**
 * Files that MAY name the forbidden identifiers.
 *
 * TWO, AND THE SECOND IS THE INTERESTING ONE. `lib/supabase/database.types.ts` is GENERATED by
 * introspecting the schema, so it declares a TypeScript type for every table in `public` — the
 * research ones included — and every module that touches Supabase imports it. Excluding it is
 * therefore not a hole: a type declaration is not a read, the file contains no query, and it cannot
 * be hand-edited without `db:check-types` failing on the diff. What this gate is actually looking
 * for is a QUERY on the public path, and that is still caught: the query lives in the file that
 * writes it, not in the type file it borrows a name from.
 *
 * The alternative — matching only `.from('research_…')` and `rpc('research…')` — was rejected
 * because it would pass an import of `lib/scraper/**`, which is the failure most worth catching.
 */
const ALLOWED = new Set([
  relative(ROOT, join(ROOT, 'scripts', 'search', 'check-search-scope.mjs')),
  relative(ROOT, join(ROOT, 'lib', 'supabase', 'database.types.ts')),
])

const EXTENSIONS = ['.tsx', '.ts', '.mjs', '.js', '.jsx']

function resolveSpecifier(specifier, fromFile) {
  const base = specifier.startsWith('@/')
    ? join(ROOT, specifier.slice(2))
    : specifier.startsWith('.')
      ? resolve(dirname(fromFile), specifier)
      : null
  if (base === null) return null

  for (const extension of EXTENSIONS) {
    const candidate = `${base}${extension}`
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate
  }
  if (existsSync(base) && statSync(base).isDirectory()) {
    for (const extension of EXTENSIONS) {
      const candidate = join(base, `index${extension}`)
      if (existsSync(candidate) && statSync(candidate).isFile()) return candidate
    }
  }
  if (existsSync(base) && statSync(base).isFile()) return base
  return null
}

const IMPORT = /(?:^|\n)\s*(?:import|export)\s[^;\n]*?from\s*['"]([^'"]+)['"]/g
const BARE_IMPORT = /(?:^|\n)\s*import\s*['"]([^'"]+)['"]/g

const seen = new Set()
const problems = []

function walk(file) {
  if (seen.has(file)) return
  seen.add(file)

  const raw = readFileSync(file, 'utf8')
  const code = stripCommentsAndStrings(raw)
  const rel = relative(ROOT, file)

  if (!ALLOWED.has(rel)) {
    const match = FORBIDDEN.exec(code)
    if (match) {
      const line = code.slice(0, match.index).split('\n').length
      problems.push(
        `${rel}:${line}: "${match[0]}" appears on the PUBLIC search path.\n` +
          '      The research corpus has its own index (research_search_documents), no anon policy,\n' +
          '      and no route a visitor can reach. If a Studio surface needs it, register a provider\n' +
          '      under components/studio/command/ — not a read from the public search path.',
      )
    }
    FORBIDDEN.lastIndex = 0
  }

  for (const pattern of [IMPORT, BARE_IMPORT]) {
    pattern.lastIndex = 0
    let match
    while ((match = pattern.exec(raw)) !== null) {
      const resolved = resolveSpecifier(match[1], file)
      if (resolved !== null) walk(resolved)
    }
  }
}

for (const entry of ENTRIES) {
  if (!existsSync(entry)) {
    problems.push(`${relative(ROOT, entry)}: does not exist — the gate is walking nothing`)
    continue
  }
  walk(entry)
}

if (problems.length > 0) {
  console.error(`\n✗ ${problems.length} search-scope problem(s):\n`)
  for (const problem of problems) console.error(`    ${problem}`)
  console.error('')
  process.exit(1)
}

console.log(
  `✓ search scope: no research identifier in the ${seen.size} modules reachable from the ` +
    `${ENTRIES.length} public search entry points`,
)
